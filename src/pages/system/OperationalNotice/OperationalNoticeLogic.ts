import { useCallback, useEffect, useMemo, useState } from 'react';
import { useIonViewWillEnter } from '@ionic/react';
import { useUser } from '../../../contexts/UserContext';
import { useToast } from '../../../hooks/useToast';
import { notifyDataChanged, onDataChanged } from '../../../utils/refreshBus';
import { hermosilloTodayISO } from '../../../utils/format';
import {
  finalizeOperationalNotice, getAllOperationalNotices, updateOperationalNotice, type OperationalNotice,
} from '../../../api/operationalNoticeApi';
import {
  getAllOperationalNoticeTemplates, type OperationalNoticeTemplate,
} from '../../../api/operationalNoticeTemplateApi';
import { MESSAGE_MAX, RESUMPTION_TEMPLATE_KEY, STATE_GROUPS, TITLE_MAX, hasPlaceholders } from './OperationalNoticeConstants';
import { useNoticeWizard } from './useNoticeWizard';
import { useTemplateAdmin } from './useTemplateAdmin';

const PLATFORM_COMPANY_ID = 1008;

/**
 * Avisos operativos — temporary situations of this company (closed today for lack of
 * water, special hours…) that the WhatsApp/voice agents tell customers before the
 * regular schedule. Generated by posgmo-factory (PRD prd_operationalNotice.json) and
 * rewritten by hand to the repo rules.
 */
export const useOperationalNotice = () => {
  const { companyId, companyName, roleCode } = useUser();
  const { showToast, toastProps } = useToast({ defaultColor: 'success' });

  const [notices, setNotices] = useState<OperationalNotice[]>([]);
  const [templates, setTemplates] = useState<OperationalNoticeTemplate[]>([]);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState(false);
  const [segment, setSegment] = useState<'avisos' | 'plantillas'>('avisos');
  const [openGroups, setOpenGroups] = useState<string[]>(['vigentes', 'programados']);

  // UI hints only — the backend enforces both.
  const canEdit = roleCode === 'admin' || roleCode === 'manager';
  const isPlatformAdmin = companyId === PLATFORM_COMPANY_ID && roleCode === 'admin';

  const load = useCallback(async () => {
    if (!companyId) return;
    setLoadError(false);
    try {
      const [list, lib] = await Promise.all([
        getAllOperationalNotices(companyId, true),
        getAllOperationalNoticeTemplates(isPlatformAdmin ? 'all' : 'activo'),
      ]);
      setNotices(list);
      setTemplates(lib);
    } catch {
      setLoadError(true);
    } finally {
      setLoading(false);
    }
  }, [companyId, isPlatformAdmin]);

  useIonViewWillEnter(() => { load(); });
  useEffect(() => { load(); }, [load]);
  useEffect(() => onDataChanged(() => { load(); }), [load]);

  const afterMutation = (message: string) => {
    showToast(message);
    notifyDataChanged('operationalNotices');
  };
  const onError = (message: string) => showToast(message, 'danger');

  const wizard = useNoticeWizard({ companyId, companyName, onPublished: afterMutation, onError });
  const templateAdmin = useTemplateAdmin({ onSaved: afterMutation, onError });
  const activeTemplates = useMemo(() => templates.filter(t => t.status === 'activo'), [templates]);

  const groups = useMemo(() => STATE_GROUPS
    .map(g => ({ ...g, notices: notices.filter(n => g.states.includes(n.state)) }))
    .filter(g => g.notices.length > 0), [notices]);
  const currentCount = notices.filter(n => n.state === 'vigente').length;
  const templateName = (id: number | null) => templates.find(t => t.operationalNoticeTemplateId === id)?.name ?? '';

  // ── Edit / extend an existing notice ───────────────────────────────────────
  const [editing, setEditing] = useState<OperationalNotice | null>(null);
  const [editForm, setEditForm] = useState({
    title: '', customerMessage: '', startDate: '', endDate: '', useHours: false, startTime: '', endTime: '',
    blocksReservations: false,
  });
  const [savingEdit, setSavingEdit] = useState(false);

  const openEdit = (n: OperationalNotice) => {
    setEditing(n);
    setEditForm({
      title: n.title, customerMessage: n.customerMessage, startDate: n.startDate, endDate: n.endDate,
      useHours: !!n.startTime, startTime: n.startTime, endTime: n.endTime, blocksReservations: n.blocksReservations,
    });
  };
  const closeEdit = () => { if (!savingEdit) setEditing(null); };
  const setEditField = <K extends keyof typeof editForm>(key: K, value: (typeof editForm)[K]) =>
    setEditForm(f => ({ ...f, [key]: value }));

  const today = hermosilloTodayISO();
  const editValid = !!editForm.title.trim() && !!editForm.customerMessage.trim()
    && editForm.title.length <= TITLE_MAX && editForm.customerMessage.length <= MESSAGE_MAX
    && !hasPlaceholders(editForm.customerMessage)
    && !!editForm.startDate && !!editForm.endDate && editForm.endDate >= editForm.startDate && editForm.endDate >= today
    && (!editForm.useHours || (!!editForm.startTime && !!editForm.endTime && editForm.endTime > editForm.startTime));

  const saveEdit = async () => {
    if (!editing || !editValid || savingEdit) return;
    setSavingEdit(true);
    try {
      await updateOperationalNotice(companyId, editing.operationalNoticeId, {
        title: editForm.title.trim(),
        customerMessage: editForm.customerMessage.trim(),
        startDate: editForm.startDate,
        endDate: editForm.endDate,
        startTime: editForm.useHours ? editForm.startTime : '',
        endTime: editForm.useHours ? editForm.endTime : '',
        blocksReservations: editing.noticeType === 'cierre' ? editForm.blocksReservations : false,
      });
      setEditing(null);
      afterMutation(editForm.endDate !== editing.endDate ? 'Vigencia actualizada' : 'Aviso actualizado');
    } catch (e) {
      onError((e as Error).message || 'No se pudo actualizar el aviso');
    } finally {
      setSavingEdit(false);
    }
  };

  // ── Finalize early (IonAlert confirm), then offer a "Reanudación" notice ──
  const [finalizing, setFinalizing] = useState<OperationalNotice | null>(null);
  const [finalizingId, setFinalizingId] = useState<number | null>(null);
  const [offerResumption, setOfferResumption] = useState(false);
  const resumptionTemplate = activeTemplates.find(t => t.templateKey === RESUMPTION_TEMPLATE_KEY) ?? null;

  const finalize = async (n: OperationalNotice) => {
    setFinalizingId(n.operationalNoticeId);
    try {
      await finalizeOperationalNotice(companyId, n.operationalNoticeId);
      afterMutation('Aviso finalizado. Los agentes ya no lo usan.');
      if (n.noticeType === 'cierre' && resumptionTemplate) setOfferResumption(true);
    } catch (e) {
      onError((e as Error).message || 'No se pudo finalizar el aviso');
    } finally {
      setFinalizingId(null);
    }
  };

  const publishResumption = () => {
    setOfferResumption(false);
    if (resumptionTemplate) wizard.start(resumptionTemplate);
  };

  return {
    companyName, notices, templates, activeTemplates, groups, currentCount, templateName,
    loading, loadError, load, segment, setSegment, openGroups, setOpenGroups,
    canEdit, isPlatformAdmin, wizard, templateAdmin,
    editing, editForm, setEditField, editValid, savingEdit, openEdit, closeEdit, saveEdit,
    finalizing, setFinalizing, finalizingId, finalize, offerResumption, setOfferResumption, publishResumption,
    toastProps,
  };
};

export type OperationalNoticeVM = ReturnType<typeof useOperationalNotice>;
