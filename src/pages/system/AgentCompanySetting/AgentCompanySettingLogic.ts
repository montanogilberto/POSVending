import { useCallback, useEffect, useMemo, useState } from 'react';
import { useIonViewWillEnter } from '@ionic/react';
import { useUser } from '../../../contexts/UserContext';
import { useToast } from '../../../hooks/useToast';
import { notifyDataChanged, onDataChanged } from '../../../utils/refreshBus';
import { getAllAgents, type Agent } from '../../../api/agentApi';
import {
  DISPLAY_NAME_MAX, EXTRA_INSTRUCTIONS_MAX, getAllAgentCompanySettings, saveAgentCompanySetting,
  type AgentCompanySetting,
} from '../../../api/agentCompanySettingApi';

export interface AgentWithSettings {
  agent: Agent;
  setting: AgentCompanySetting | null;
}

/**
 * Agentes IA › Ajustes para mi empresa. Generated by posgmo-factory
 * (PRD prd_agentCompanySetting.json) and fixed by hand.
 * Active catalog agents merged with this company's settings rows.
 */
export const useAgentCompanySetting = () => {
  const { companyId, roleCode } = useUser();
  const { showToast, toastProps } = useToast({ defaultColor: 'success' });

  const [items, setItems] = useState<AgentWithSettings[]>([]);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState(false);
  const [saving, setSaving] = useState(false);
  const [editing, setEditing] = useState<AgentWithSettings | null>(null);
  const [displayName, setDisplayName] = useState('');
  const [extraInstructions, setExtraInstructions] = useState('');

  // UI hint only — the backend checks the company role from the session token.
  const canEdit = roleCode === 'admin' || roleCode === 'manager';

  const load = useCallback(async () => {
    if (!companyId) return;
    setLoadError(false);
    try {
      const [agents, settings] = await Promise.all([
        getAllAgents({ status: 'activo' }),
        getAllAgentCompanySettings(companyId),
      ]);
      setItems(agents.map(agent => ({ agent, setting: settings.find(s => s.agentId === agent.agentId) ?? null })));
    } catch {
      setLoadError(true);
    } finally {
      setLoading(false);
    }
  }, [companyId]);

  useIonViewWillEnter(() => { load(); });
  useEffect(() => { load(); }, [load]);
  useEffect(() => onDataChanged(() => { load(); }), [load]);

  const configuredCount = useMemo(() => items.filter(i => i.setting).length, [items]);

  const open = (item: AgentWithSettings) => {
    setEditing(item);
    setDisplayName(item.setting?.displayName ?? '');
    setExtraInstructions(item.setting?.extraInstructions ?? '');
  };

  const close = () => { if (!saving) setEditing(null); };

  const formValid = displayName.length <= DISPLAY_NAME_MAX && extraInstructions.length <= EXTRA_INSTRUCTIONS_MAX;

  const save = async () => {
    if (!editing || !companyId || !canEdit || !formValid || saving) return;
    setSaving(true);
    try {
      await saveAgentCompanySetting({
        companyId, agentId: editing.agent.agentId,
        displayName: displayName.trim(), extraInstructions: extraInstructions.trim(),
      });
      showToast('Ajustes guardados');
      notifyDataChanged('agents');
      setEditing(null);
    } catch (e) {
      showToast((e as Error).message || 'No se pudieron guardar los ajustes', 'danger');
    } finally {
      setSaving(false);
    }
  };

  return {
    items, configuredCount, loading, loadError, load, saving, canEdit,
    editing, open, close, displayName, setDisplayName, extraInstructions, setExtraInstructions, formValid, save,
    toastProps,
  };
};

export type AgentCompanySettingVM = ReturnType<typeof useAgentCompanySetting>;
