import { useCallback, useEffect, useMemo, useState } from 'react';
import { useIonRouter, useIonViewWillEnter } from '@ionic/react';
import { useUser } from '../../../contexts/UserContext';
import { useToast } from '../../../hooks/useToast';
import { notifyDataChanged, onDataChanged } from '../../../utils/refreshBus';
import {
  createAgent, getAllAgents, retireAgent, updateAgent, type Agent, type AgentArea, type AgentInput,
} from '../../../api/agentApi';
import { getAllAgentCompanySettings } from '../../../api/agentCompanySettingApi';
import { AREAS, EMPTY_AGENT, PLATFORM_COMPANY_ID, type StatusFilter } from './AgentConstants';

/**
 * Agentes IA — the platform catalog of LoanAgents_SmartLoans agents.
 * Generated by posgmo-factory (PRD prd_agent.json) and fixed by hand.
 * The catalog is small (~20 rows): it loads once and search/area filter run locally.
 */
export const useAgent = () => {
  const { companyId, roleCode } = useUser();
  const { showToast, toastProps } = useToast({ defaultColor: 'success' });
  const router = useIonRouter();

  const [agents, setAgents] = useState<Agent[]>([]);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState(false);
  const [saving, setSaving] = useState(false);
  const [search, setSearch] = useState('');
  const [area, setArea] = useState<AgentArea | 'all'>('all');
  const [status, setStatus] = useState<StatusFilter>('all');
  /** agentIds this company customized in /ai-agents/settings ("Personalizado"). */
  const [customizedIds, setCustomizedIds] = useState<Set<number>>(new Set());
  const [actionsFor, setActionsFor] = useState<Agent | null>(null);

  const [modalOpen, setModalOpen] = useState(false);
  const [editing, setEditing] = useState<Agent | null>(null);
  const [form, setForm] = useState<AgentInput>(EMPTY_AGENT);
  const [confirmRetire, setConfirmRetire] = useState(false);

  // UI hint only — the backend refuses catalog writes from anyone else.
  const canEditCatalog = companyId === PLATFORM_COMPANY_ID && roleCode === 'admin';

  const load = useCallback(async () => {
    setLoadError(false);
    try {
      // Company settings only add the "Personalizado" chip: if they fail
      // (e.g. table not deployed yet) the catalog still renders.
      const [list, settings] = await Promise.all([
        getAllAgents(),
        companyId ? getAllAgentCompanySettings(companyId).catch(() => []) : Promise.resolve([]),
      ]);
      setAgents(list);
      setCustomizedIds(new Set(settings.map(s => s.agentId)));
    } catch {
      setLoadError(true);
    } finally {
      setLoading(false);
    }
  }, [companyId]);

  useIonViewWillEnter(() => { load(); });
  useEffect(() => { load(); }, [load]);
  useEffect(() => onDataChanged(() => { load(); }), [load]);

  // Search + status apply everywhere; the area filter only narrows the list,
  // so the area tabs can show how many matches each area has.
  const matching = useMemo(() => {
    const q = search.trim().toLowerCase();
    return agents.filter(a =>
      (status === 'all' || a.status === status)
      && (!q || `${a.name} ${a.description} ${a.agentKey} ${a.endpoint} ${a.model}`.toLowerCase().includes(q)));
  }, [agents, search, status]);

  const areaCounts = useMemo(() => {
    const counts: Record<string, number> = { all: matching.length };
    for (const a of matching) counts[a.area] = (counts[a.area] ?? 0) + 1;
    return counts;
  }, [matching]);

  const groups = useMemo(() => {
    const visible = matching.filter(a => area === 'all' || a.area === area);
    return AREAS
      .map(g => ({ ...g, agents: visible.filter(a => a.area === g.value) }))
      .filter(g => g.agents.length > 0);
  }, [matching, area]);

  const totals = useMemo(() => ({
    all: agents.length,
    active: agents.filter(a => a.status === 'activo').length,
    retired: agents.filter(a => a.status === 'retirado').length,
  }), [agents]);

  const isCustomized = (agent: Agent) => customizedIds.has(agent.agentId);

  // Area sections start collapsed (the catalog grows per product/company).
  // While searching or filtering by one area every matching section opens,
  // so results are never hidden behind a closed header.
  const [openGroups, setOpenGroups] = useState<string[]>([]);
  const autoExpand = search.trim() !== '' || area !== 'all' || status !== 'all';
  const expandedGroups = autoExpand ? groups.map(g => g.value) : openGroups;
  const setExpandedGroups = (value: string | string[] | null | undefined) => {
    if (autoExpand) return;
    setOpenGroups(Array.isArray(value) ? value : value ? [value] : []);
  };
  const allExpanded = groups.length > 0 && groups.every(g => expandedGroups.includes(g.value));
  const toggleAllGroups = () => setOpenGroups(allExpanded ? [] : groups.map(g => g.value));

  const openCreate = () => {
    setEditing(null);
    setForm(EMPTY_AGENT);
    setModalOpen(true);
  };

  const openDetail = (agent: Agent) => {
    setEditing(agent);
    setForm({
      agentKey: agent.agentKey, name: agent.name, description: agent.description, area: agent.area,
      endpoint: agent.endpoint, model: agent.model, customerFacing: agent.customerFacing,
    });
    setModalOpen(true);
  };

  const closeModal = () => {
    if (saving) return;
    setModalOpen(false);
    setConfirmRetire(false);
  };

  const setField = <K extends keyof AgentInput>(key: K, value: AgentInput[K]) =>
    setForm(f => ({ ...f, [key]: value }));

  const endpointOk = form.endpoint.trim().startsWith('/') && !form.endpoint.includes('://');
  const formValid = !!form.agentKey.trim() && /^[a-z0-9_]+$/.test(form.agentKey.trim())
    && !!form.name.trim() && endpointOk;

  const save = async () => {
    if (!canEditCatalog || !formValid || saving) return;
    setSaving(true);
    try {
      const input = {
        ...form, agentKey: form.agentKey.trim(), name: form.name.trim(), description: form.description.trim(),
        endpoint: form.endpoint.trim(), model: form.model.trim(),
      };
      if (editing) {
        const { agentKey: _key, ...rest } = input;
        await updateAgent(editing.agentId, rest);
        showToast('Agente actualizado');
      } else {
        await createAgent(input);
        showToast('Agente creado');
      }
      notifyDataChanged('agents');
      setModalOpen(false);
    } catch (e) {
      showToast((e as Error).message || 'No se pudo guardar el agente', 'danger');
    } finally {
      setSaving(false);
    }
  };

  const retire = async () => {
    if (!canEditCatalog || !editing || saving) return;
    setSaving(true);
    try {
      await retireAgent(editing.agentId);
      showToast('Agente retirado');
      notifyDataChanged('agents');
      setModalOpen(false);
    } catch (e) {
      showToast((e as Error).message || 'No se pudo retirar el agente', 'danger');
    } finally {
      setSaving(false);
      setConfirmRetire(false);
    }
  };

  // ⋮ menu on each card.
  const actionButtons = (() => {
    const agent = actionsFor;
    if (!agent) return [];
    const buttons: { text: string; role?: string; handler?: () => void }[] = [
      { text: canEditCatalog ? 'Ver / editar' : 'Ver detalle', handler: () => openDetail(agent) },
      { text: 'Ajustes para mi empresa', handler: () => router.push('/ai-agents/settings') },
    ];
    if (agent.area === 'whatsapp') {
      buttons.push({ text: 'Abrir Agente WhatsApp', handler: () => router.push('/whatsapp-agent') });
    }
    buttons.push({ text: 'Cancelar', role: 'cancel' });
    return buttons;
  })();

  return {
    actionButtons,
    agents, groups, areaCounts, totals, isCustomized, expandedGroups, setExpandedGroups, allExpanded, autoExpand,
    toggleAllGroups, loading, loadError, load, saving,
    search, setSearch, area, setArea, status, setStatus, actionsFor, setActionsFor,
    modalOpen, editing, form, setField, formValid, endpointOk, openCreate, openDetail, closeModal, save,
    confirmRetire, setConfirmRetire, retire,
    canEditCatalog, toastProps,
  };
};

export type AgentVM = ReturnType<typeof useAgent>;
